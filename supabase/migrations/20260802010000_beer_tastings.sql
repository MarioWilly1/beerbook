-- ────────────────────────────────────────────────────────────
-- 5. entry_flags: nueva columna para referenciar la cata puntual.
-- ────────────────────────────────────────────────────────────
ALTER TABLE public.entry_flags ADD COLUMN IF NOT EXISTS tasting_id bigint REFERENCES public.beer_tastings(id) ON DELETE SET NULL;

-- Vincula los flags automáticos ya existentes con la cata backfillada
-- correspondiente, para no perder la referencia.
UPDATE public.entry_flags ef
SET tasting_id = bt.id
FROM public.beer_tastings bt
WHERE bt.user_id = ef.user_id AND bt.beer_id = ef.beer_id
  AND ef.source IN ('duplicate_photo', 'velocity')
  AND ef.tasting_id IS NULL;

DROP INDEX IF EXISTS public.entry_flags_auto_unique;
CREATE UNIQUE INDEX entry_flags_auto_unique
  ON public.entry_flags (tasting_id, source)
  WHERE source IN ('duplicate_photo', 'velocity') AND tasting_id IS NOT NULL;

-- ────────────────────────────────────────────────────────────
-- 6. Anti-trampa: se muda de user_beers a beer_tastings — ahora cada
-- fila SÍ representa un evento real de carga, cosa que ya no es
-- cierto para user_beers una vez que existen catas repetidas.
-- ────────────────────────────────────────────────────────────
DROP TRIGGER IF EXISTS trg_check_photo_flags ON public.user_beers;

CREATE OR REPLACE FUNCTION public.check_photo_flags()
RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' AS $$
DECLARE
  v_dup_beer_id bigint;
  v_dup_distance int;
  v_recent_count int;
BEGIN
  IF NEW.photo_hash IS NOT NULL THEN
    SELECT beer_id, bit_count((photo_hash # NEW.photo_hash)::bit(64))
      INTO v_dup_beer_id, v_dup_distance
    FROM public.beer_tastings
    WHERE user_id = NEW.user_id
      AND beer_id <> NEW.beer_id
      AND photo_hash IS NOT NULL
      AND bit_count((photo_hash # NEW.photo_hash)::bit(64)) <= 5
    ORDER BY bit_count((photo_hash # NEW.photo_hash)::bit(64))
    LIMIT 1;

    IF v_dup_beer_id IS NOT NULL THEN
      INSERT INTO public.entry_flags (user_id, beer_id, tasting_id, source, reason)
      VALUES (
        NEW.user_id, NEW.beer_id, NEW.id, 'duplicate_photo',
        format('Foto casi idéntica (distancia %s/64) a la usada en beer_id=%s', v_dup_distance, v_dup_beer_id)
      )
      ON CONFLICT (tasting_id, source) WHERE source IN ('duplicate_photo', 'velocity') AND tasting_id IS NOT NULL
      DO UPDATE SET reason = EXCLUDED.reason, created_at = now(), status = 'pending';
    END IF;
  END IF;

  SELECT count(*) INTO v_recent_count
  FROM public.beer_tastings
  WHERE user_id = NEW.user_id
    AND user_photo_url IS NOT NULL
    AND created_at >= now() - interval '1 hour';

  IF v_recent_count > 10 THEN
    INSERT INTO public.entry_flags (user_id, beer_id, tasting_id, source, reason)
    VALUES (
      NEW.user_id, NEW.beer_id, NEW.id, 'velocity',
      format('%s entradas verificadas en la última hora', v_recent_count)
    )
    ON CONFLICT (tasting_id, source) WHERE source IN ('duplicate_photo', 'velocity') AND tasting_id IS NOT NULL
    DO UPDATE SET reason = EXCLUDED.reason, created_at = now(), status = 'pending';
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_check_photo_flags_tastings ON public.beer_tastings;
CREATE TRIGGER trg_check_photo_flags_tastings
  AFTER INSERT ON public.beer_tastings
  FOR EACH ROW
  WHEN (NEW.user_photo_url IS NOT NULL)
  EXECUTE FUNCTION public.check_photo_flags();

-- ────────────────────────────────────────────────────────────
-- 7. admin_unverify_entry: si el flag referencia una cata puntual,
-- limpiar esa cata (y, si además es la representativa vigente,
-- limpiar también user_beers para que la tarjeta principal lo refleje
-- al toque). Si no tiene tasting_id (reporte comunitario, sigue
-- apuntando solo a la fila representativa), mismo comportamiento de
-- siempre.
-- ────────────────────────────────────────────────────────────
CREATE OR REPLACE FUNCTION public.admin_unverify_entry(p_flag_id uuid)
RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public' AS $$
DECLARE
  v_user_id uuid;
  v_beer_id bigint;
  v_tasting_id bigint;
BEGIN
  IF NOT is_admin() THEN
    RAISE EXCEPTION 'No autorizado';
  END IF;

  SELECT user_id, beer_id, tasting_id INTO v_user_id, v_beer_id, v_tasting_id
  FROM public.entry_flags WHERE id = p_flag_id;

  IF v_user_id IS NULL THEN
    RAISE EXCEPTION 'Reporte no encontrado';
  END IF;

  IF v_tasting_id IS NOT NULL THEN
    UPDATE public.beer_tastings SET user_photo_url = NULL, photo_hash = NULL WHERE id = v_tasting_id;
  END IF;

  UPDATE public.user_beers
  SET user_photo_url = NULL, photo_hash = NULL
  WHERE user_id = v_user_id AND beer_id = v_beer_id;

  UPDATE public.entry_flags
  SET status = 'confirmed', reviewed_at = now(), reviewed_by = auth.uid()
  WHERE id = p_flag_id;
END;
$$;
